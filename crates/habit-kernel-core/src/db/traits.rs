//! Данные трейты описывают работу с примитивной БД на основе JSON.
//!

use std::path::Path;

use crate::{
    habit::Habit,
    io::{Load, Save},
};

/// Описание геттеров без мутабельности.
///
/// Все методы — только чтение: они возвращают заимствованные ссылки на
/// привычки и не изменяют состояние базы. Если подходящей привычки нет,
/// возвращается `None`.
pub trait DataBaseMetadata {
    /// Выбранная (текущая) привычка.
    ///
    /// Возвращает `None`, если привычка не выбрана либо если сохранённый
    /// идентификатор больше не соответствует ни одной записи.
    fn get_current_habit(&self) -> Option<&Habit>;

    /// Привычка по её позиции в списке.
    ///
    /// Возвращает `None`, если `index` вышел за границы списка.
    fn get_by_idx(&self, index: usize) -> Option<&Habit>;

    /// Привычка по её уникальному идентификатору.
    ///
    /// Возвращает `None`, если привычки с таким `id` нет.
    fn get_by_id(&self, id: uuid::Uuid) -> Option<&Habit>;

    /// Итератор по всем привычкам в порядке их добавления.
    fn iter(&self) -> std::slice::Iter<'_, Habit>;
}

/// Получение геттеров с мутабельностью.
///
/// Те же выборки, что и в [`DataBaseMetadata`], но возвращают мутабельные
/// ссылки и требуют `&mut self`. Если подходящей привычки нет, возвращается
/// `None`.
pub trait DataBaseMetadataMut {
    /// Мутабельный доступ к выбранной (текущей) привычке.
    ///
    /// Возвращает `None`, если привычка не выбрана либо если сохранённый
    /// идентификатор больше не соответствует ни одной записи.
    fn get_mut_current_habit(&mut self) -> Option<&mut Habit>;

    /// Мутабельный доступ к привычке по её позиции в списке.
    ///
    /// Возвращает `None`, если `index` вышел за границы списка.
    fn get_mut_by_idx(&mut self, index: usize) -> Option<&mut Habit>;

    /// Мутабельный доступ к привычке по её уникальному идентификатору.
    ///
    /// Возвращает `None`, если привычки с таким `id` нет.
    fn get_mut_by_id(&mut self, id: uuid::Uuid) -> Option<&mut Habit>;

    /// Мутабельный итератор по всем привычкам в порядке их добавления.
    fn iter_mut(&mut self) -> std::slice::IterMut<'_, Habit>;
}

/// Отправка запросов на полноценное изменение базы данных.
///
/// В отличие от геттеров [`DataBaseMetadata`]/[`DataBaseMetadataMut`],
/// методы этого трейта меняют состав или состояние базы. `P` задаёт путь
/// (или его представление), по которому база сохраняется и загружается,
/// поэтому трейт требует реализации [`Save<P>`] и [`Load<P>`].
pub trait QueryExecutor<P>: Save<P> + Load<P>
where
    P: AsRef<Path>,
{
    /// Создаёт новую привычку с именем `name` и добавляет её в конец списка.
    ///
    /// Новая привычка становится доступной через геттеры, но не делается
    /// текущей автоматически (для выбора используйте [`QueryExecutor::select_habit`]).
    fn add_habit(&mut self, name: &str);

    /// Делает привычку с идентификатором `id` текущей.
    ///
    /// Если привычки с таким `id` нет, текущая привычка сбрасывается
    /// в `None`.
    fn select_habit(&mut self, id: uuid::Uuid);

    /// Отмечает выполнение текущей привычки: увеличивает счётчик за
    /// сегодняшнюю дату.
    ///
    /// Ничего не делает, если текущая привычка не выбрана.
    fn current_done(&mut self);

    /// Удаляет привычку с идентификатором `id`.
    ///
    /// Если привычки с таким `id` нет, ничего не происходит. Поле
    /// «текущей» привычки при этом не изменяется: если удалена именно она,
    /// [`DataBaseMetadata::get_current_habit`] будет возвращать `None`,
    /// так как сохранённый `id` больше не разрешается в запись.
    fn del_by_id(&mut self, id: uuid::Uuid);
}
